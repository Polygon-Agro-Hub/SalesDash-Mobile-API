/**
 * Sends a crash report email to all configured recipients.
 */
async function sendCrashReport(reportData) {
  const { transporter, from, isTestAccount } = await getTransporter();

  const subject = `🚨 [SalesDash Crash] ${reportData.errorMessage ? reportData.errorMessage.substring(0, 60) : "App Crash"} (${reportData.screenName || "General"})`;
  const html = buildCrashEmailHtml(reportData);

  const mailOptions = {
    from,
    to: CRASH_REPORT_RECIPIENTS,
    subject,
    html,
  };

  const info = await transporter.sendMail(mailOptions);

  let previewUrl = null;
  if (isTestAccount) {
    previewUrl = nodemailer.getTestMessageUrl(info);
    console.log("📧 [CrashReporter] Test email sent via Ethereal!");
    console.log("🔗 Preview URL to view sent email in browser:", previewUrl);
  } else {
    console.log(`✅ [CrashReporter] Crash email successfully sent to: ${CRASH_REPORT_RECIPIENTS.join(", ")} (MessageID: ${info.messageId})`);
  }

  return {
    success: true,
    messageId: info.messageId,
    recipients: CRASH_REPORT_RECIPIENTS,
    previewUrl,
    isTestAccount,
  };
}

module.exports = {
  sendCrashReport,
  buildCrashEmailHtml,
};
